-- Session #1

BEGIN;

UPDATE pizzeria
SET rating = 4
WHERE id = 1;

UPDATE pizzeria
SET rating = 4
WHERE id = 2;

COMMIT;


-- Session #2

BEGIN;

UPDATE pizzeria
SET rating = 4
WHERE id = 2;

UPDATE pizzeria
SET rating = 4
WHERE id = 1;

COMMIT;
















-- ============================================================
-- Session #1 (первое окно терминала с psql)
-- Уровень изоляции: по умолчанию (READ COMMITTED)
-- ============================================================

/*
    Шаг 1: Открываем транзакцию.
    Задание разрешает любой уровень изоляции,
    поэтому используем дефолтный (READ COMMITTED).
*/
BEGIN;

/*
    Шаг 3: Обновляем строку с id = 1 (Pizza Hut).
    PostgreSQL БЛОКИРУЕТ эту строку — другие транзакции
    не смогут её изменить, пока мы не сделаем COMMIT.
    Session #1 теперь «держит» id = 1.
*/
UPDATE pizzeria
SET rating = 4
WHERE id = 1;

/*
    Шаг 5: Пытаемся обновить строку с id = 2 (Dominos).
    Но Session #2 уже заблокировал эту строку на шаге 4!
    Команда ЗАВИСНЕТ — Session #1 ждёт, пока Session #2
    освободит строку id = 2.

    В этот момент:
    Session #1 ДЕРЖИТ id = 1, ЖДЁТ id = 2
    Session #2 ДЕРЖИТ id = 2, ЖДЁТ id = 1 (шаг 6)

    Это и есть DEADLOCK (взаимоблокировка) —
    замкнутый круг ожидания. Ни одна транзакция
    не может продолжить, потому что каждая ждёт другую.

    PostgreSQL обнаруживает deadlock и принудительно
    УБИВАЕТ одну из транзакций (обычно Session #2),
    после чего Session #1 разблокируется и продолжает.
*/
UPDATE pizzeria
SET rating = 4
WHERE id = 2;

/*
    Шаг 7: Фиксируем изменения.
    Session #1 выжил — COMMIT проходит успешно.
*/
COMMIT;


-- ============================================================
-- Session #2 (второе окно терминала с psql)
-- Уровень изоляции: по умолчанию (READ COMMITTED)
-- ============================================================

/*
    Шаг 2: Открываем транзакцию во втором сеансе.
*/
BEGIN;

/*
    Шаг 4: Обновляем строку с id = 2 (Dominos).
    PostgreSQL БЛОКИРУЕТ эту строку.
    Session #2 теперь «держит» id = 2.
    Обрати внимание: Session #1 начал с id = 1,
    а Session #2 начал с id = 2 — ОБРАТНЫЙ порядок.
    Именно перекрёстный порядок создаёт deadlock.
*/
UPDATE pizzeria
SET rating = 4
WHERE id = 2;

/*
    Шаг 6: Пытаемся обновить строку с id = 1 (Pizza Hut).
    Но Session #1 уже заблокировал эту строку на шаге 3!
    PostgreSQL обнаруживает DEADLOCK и выбрасывает ошибку:
    ERROR: deadlock detected (обнаружена взаимоблокировка)
    Транзакция Session #2 помечается как сломанная.
*/
UPDATE pizzeria
SET rating = 4
WHERE id = 1;

/*
    Шаг 8: Пытаемся зафиксировать.
    Результат: ROLLBACK — транзакция уже сломана ошибкой
    deadlock, PostgreSQL автоматически откатывает её.

    Вывод: deadlock возникает при ПЕРЕКРЁСТНОЙ блокировке:
    Session #1: id=1 → id=2
    Session #2: id=2 → id=1
    Если бы оба шли в одном порядке (оба id=1 → id=2),
    второй просто подождал бы первого, без deadlock.
*/
COMMIT;


